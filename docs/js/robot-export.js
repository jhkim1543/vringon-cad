/* ==========================================================================
   CIR back-ends: one canonical asset graph → USD / URDF / MJCF / GLB.

   Frame convention (the part that silently breaks most generated URDFs):
   every link frame is AXIS-ALIGNED with the world and placed at the joint that
   attaches it (the root link frame sits at the world origin). So
     · joint origin  = jointWorld − parentFrameWorld
     · visual origin = geometryWorld − ownFrameWorld
     · axis          = world axis, unchanged (frames never rotate)
   which keeps the kinematic chain exact without ever composing rotations.
   ========================================================================== */
import * as THREE from "three";
import { STLExporter } from "three/addons/exporters/STLExporter.js";
import { zipSync, strToU8 } from "three/addons/libs/fflate.module.js";

const MM_TO_M = 0.001;
const f = (v) => (Math.abs(v) < 1e-9 ? "0" : Number(v).toFixed(6).replace(/0+$/, "").replace(/\.$/, ""));
const xyz = (a) => `${f(a[0])} ${f(a[1])} ${f(a[2])}`;
const esc = (s) => String(s).replace(/[<>&"']/g, (c) => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;", "'": "&apos;" }[c]));

/* -------------------------------------------------------------- frames */
export function linkFrames(cir) {
  const byId = new Map(cir.links.map((l) => [l.id, l]));
  const jointOf = new Map(cir.joints.map((j) => [j.child, j]));
  const frame = new Map();
  const resolve = (id, guard = 0) => {
    if (frame.has(id)) return frame.get(id);
    if (guard > 64) return new THREE.Vector3();
    const j = jointOf.get(id);
    const pos = j ? new THREE.Vector3().fromArray(j.origin.position) : new THREE.Vector3();
    frame.set(id, pos);
    return pos;
  };
  cir.links.forEach((l) => resolve(l.id));
  // geometry centre of each link in world metres (bbox centre)
  const centre = new Map(cir.links.map((l) => [l.id, new THREE.Vector3(
    (l.bbox.min[0] + l.bbox.max[0]) / 2,
    (l.bbox.min[1] + l.bbox.max[1]) / 2,
    (l.bbox.min[2] + l.bbox.max[2]) / 2,
  )]));
  return { byId, jointOf, frame, centre };
}

/* URDF/MJCF collision primitive from the fitted shape (metres) */
function collisionShapes(link) {
  const c = link._collision;
  if (!c) return [];
  const toM = (v) => v * MM_TO_M;
  if (c.type === "sphere") return [{ kind: "sphere", radius: toM(c.params.radius), offset: [0, 0, 0] }];
  if (c.type === "cylinder" || c.type === "capsule") {
    return [{
      kind: c.type, radius: toM(c.params.radius), length: toM(c.params.length),
      axis: c.params.axis.toArray(), offset: [0, 0, 0],
    }];
  }
  if (c.type === "box") {
    return [{ kind: "box", size: c.params.half.map((h) => toM(h * 2)), offset: [0, 0, 0] }];
  }
  if (c.type === "compound_box") {
    const base = link._measured?.centre || new THREE.Vector3();
    return c.params.boxes.map((b) => ({
      kind: "box",
      size: b.half.map((h) => toM(h * 2)),
      offset: b.centre.clone().sub(base).multiplyScalar(MM_TO_M).toArray(),
    }));
  }
  return [];
}

/* -------------------------------------------------------------- URDF */
export function exportURDF(cir) {
  const { frame, centre, byId } = linkFrames(cir);
  const L = [`<?xml version="1.0"?>`,
    `<!-- generated by VRINGON Robot Asset Compiler · ${cir.assetId} -->`,
    `<robot name="${esc(cir.name)}">`];
  for (const l of cir.links) {
    const fr = frame.get(l.id);
    const geoOff = centre.get(l.id).clone().sub(fr);
    const comOff = new THREE.Vector3().fromArray(l.inertial.com).sub(fr);
    const I = l.inertial.inertia.map((r) => r.map(Number));
    L.push(`  <link name="${esc(l.id)}">`);
    L.push(`    <inertial>`);
    L.push(`      <origin xyz="${xyz(comOff.toArray())}" rpy="0 0 0"/>`);
    L.push(`      <mass value="${f(Math.max(1e-4, l.inertial.mass))}"/>`);
    L.push(`      <inertia ixx="${f(I[0][0])}" ixy="${f(I[0][1])}" ixz="${f(I[0][2])}" iyy="${f(I[1][1])}" iyz="${f(I[1][2])}" izz="${f(I[2][2])}"/>`);
    L.push(`    </inertial>`);
    L.push(`    <visual>`);
    L.push(`      <origin xyz="${xyz(fr.clone().negate().toArray())}" rpy="0 0 0"/>`);
    L.push(`      <geometry><mesh filename="meshes/${l.id}.stl" scale="0.001 0.001 0.001"/></geometry>`);
    L.push(`    </visual>`);
    for (const s of collisionShapes(l)) {
      const off = geoOff.clone().add(new THREE.Vector3().fromArray(s.offset));
      let geo = "";
      if (s.kind === "box") geo = `<box size="${xyz(s.size)}"/>`;
      else if (s.kind === "sphere") geo = `<sphere radius="${f(s.radius)}"/>`;
      else geo = `<cylinder radius="${f(s.radius)}" length="${f(s.length)}"/>`;
      L.push(`    <collision>`);
      L.push(`      <origin xyz="${xyz(off.toArray())}" rpy="0 0 0"/>`);
      L.push(`      <geometry>${geo}</geometry>`);
      L.push(`    </collision>`);
    }
    L.push(`  </link>`);
  }
  for (const j of cir.joints) {
    const pf = frame.get(j.parent) || new THREE.Vector3();
    const rel = new THREE.Vector3().fromArray(j.origin.position).sub(pf);
    const type = j.type === "continuous" ? "continuous" : j.type;
    L.push(`  <joint name="${esc(j.id)}" type="${type}">`);
    L.push(`    <parent link="${esc(j.parent)}"/>`);
    L.push(`    <child link="${esc(j.child)}"/>`);
    L.push(`    <origin xyz="${xyz(rel.toArray())}" rpy="0 0 0"/>`);
    if (type !== "fixed") L.push(`    <axis xyz="${xyz(j.axis)}"/>`);
    if (j.limits && type !== "fixed" && type !== "continuous") {
      L.push(`    <limit lower="${f(j.limits.lower)}" upper="${f(j.limits.upper)}" effort="${f(j.limits.effort)}" velocity="${f(j.limits.velocity)}"/>`);
    } else if (type === "continuous") {
      L.push(`    <limit effort="${f(j.limits?.effort ?? 120)}" velocity="${f(j.limits?.velocity ?? 3)}"/>`);
    }
    L.push(`  </joint>`);
  }
  L.push(`</robot>`);
  return L.join("\n");
}

/* -------------------------------------------------------------- USD (usda)
   Master format: rigid bodies + mass + colliders + joints + articulation root.
   Arbitrary joint axes are handled the USD way — axis token "X" plus a
   localRot that rotates X onto the measured axis. */
function quatAlignXTo(axis) {
  const q = new THREE.Quaternion().setFromUnitVectors(
    new THREE.Vector3(1, 0, 0), new THREE.Vector3().fromArray(axis).normalize());
  return [q.w, q.x, q.y, q.z];                     // USD quatf is (w, i, j, k)
}

export function exportUSDA(cir) {
  const { frame, centre } = linkFrames(cir);
  const up = cir.coordinateSystem?.upAxis === "Z" ? "Z" : "Y";
  const P = [`#usda 1.0`, `(`, `    defaultPrim = "${cir.name.replace(/\W/g, "_") || "robot"}"`,
    `    metersPerUnit = 1`, `    upAxis = "${up}"`,
    `    doc = "VRINGON Robot Asset Compiler · ${cir.assetId}"`, `)`, ``];
  const rootName = cir.name.replace(/\W/g, "_") || "robot";
  P.push(`def Xform "${rootName}" (`);
  P.push(`    prepend apiSchemas = ["PhysicsArticulationRootAPI"]`);
  P.push(`)`, `{`);
  for (const l of cir.links) {
    const fr = frame.get(l.id);
    const geoOff = centre.get(l.id).clone().sub(fr);
    const I = l.inertial.inertia.map((r) => r.map(Number));
    P.push(`    def Xform "${l.id}" (`);
    P.push(`        prepend apiSchemas = ["PhysicsRigidBodyAPI", "PhysicsMassAPI"]`);
    P.push(`    )`, `    {`);
    P.push(`        float3 xformOp:translate = (${f(fr.x)}, ${f(fr.y)}, ${f(fr.z)})`);
    P.push(`        uniform token[] xformOpOrder = ["xformOp:translate"]`);
    P.push(`        float physics:mass = ${f(Math.max(1e-4, l.inertial.mass))}`);
    P.push(`        point3f physics:centerOfMass = (${xyz(new THREE.Vector3().fromArray(l.inertial.com).sub(fr).toArray()).replace(/ /g, ", ")})`);
    P.push(`        float3 physics:diagonalInertia = (${f(I[0][0])}, ${f(I[1][1])}, ${f(I[2][2])})`);
    P.push(`        custom string vringon:semanticType = "${esc(l.semanticType || "unknown")}"`);
    P.push(`        custom string vringon:status = "${l.status}"`);
    collisionShapes(l).forEach((s, n) => {
      const off = geoOff.clone().add(new THREE.Vector3().fromArray(s.offset));
      const nm = `collision_${n}`;
      if (s.kind === "sphere") {
        P.push(`        def Sphere "${nm}" (prepend apiSchemas = ["PhysicsCollisionAPI"])`, `        {`);
        P.push(`            double radius = ${f(s.radius)}`);
      } else if (s.kind === "box") {
        P.push(`        def Cube "${nm}" (prepend apiSchemas = ["PhysicsCollisionAPI"])`, `        {`);
        P.push(`            double size = 2`);
        P.push(`            float3 xformOp:scale = (${f(s.size[0] / 2)}, ${f(s.size[1] / 2)}, ${f(s.size[2] / 2)})`);
      } else {
        P.push(`        def Cylinder "${nm}" (prepend apiSchemas = ["PhysicsCollisionAPI"])`, `        {`);
        P.push(`            double radius = ${f(s.radius)}`);
        P.push(`            double height = ${f(s.length)}`);
        P.push(`            uniform token axis = "Y"`);
      }
      P.push(`            float3 xformOp:translate = (${f(off.x)}, ${f(off.y)}, ${f(off.z)})`);
      P.push(`            uniform token[] xformOpOrder = [${s.kind === "box" ? `"xformOp:translate", "xformOp:scale"` : `"xformOp:translate"`}]`);
      P.push(`        }`);
    });
    P.push(`    }`);
  }
  for (const j of cir.joints) {
    const kind = j.type === "prismatic" ? "PhysicsPrismaticJoint"
      : j.type === "fixed" ? "PhysicsFixedJoint" : "PhysicsRevoluteJoint";
    const pf = frame.get(j.parent) || new THREE.Vector3();
    const cf = frame.get(j.child) || new THREE.Vector3();
    const jp = new THREE.Vector3().fromArray(j.origin.position);
    const lp0 = jp.clone().sub(pf), lp1 = jp.clone().sub(cf);
    P.push(`    def ${kind} "${j.id}"`, `    {`);
    P.push(`        rel physics:body0 = </${rootName}/${j.parent}>`);
    P.push(`        rel physics:body1 = </${rootName}/${j.child}>`);
    P.push(`        point3f physics:localPos0 = (${f(lp0.x)}, ${f(lp0.y)}, ${f(lp0.z)})`);
    P.push(`        point3f physics:localPos1 = (${f(lp1.x)}, ${f(lp1.y)}, ${f(lp1.z)})`);
    if (kind !== "PhysicsFixedJoint") {
      const q = quatAlignXTo(j.axis);
      P.push(`        uniform token physics:axis = "X"`);
      P.push(`        quatf physics:localRot0 = (${f(q[0])}, ${f(q[1])}, ${f(q[2])}, ${f(q[3])})`);
      P.push(`        quatf physics:localRot1 = (${f(q[0])}, ${f(q[1])}, ${f(q[2])}, ${f(q[3])})`);
      if (j.limits && j.type !== "continuous") {
        const scale = j.type === "prismatic" ? 1 : 180 / Math.PI;   // USD angles are degrees
        P.push(`        float physics:lowerLimit = ${f(j.limits.lower * scale)}`);
        P.push(`        float physics:upperLimit = ${f(j.limits.upper * scale)}`);
      }
    }
    P.push(`        custom float vringon:confidence = ${f(j.confidence.type)}`);
    P.push(`    }`);
  }
  P.push(`}`);
  return P.join("\n");
}

/* -------------------------------------------------------------- MJCF */
export function exportMJCF(cir) {
  const { frame, centre, byId } = linkFrames(cir);
  const childrenOf = new Map();
  for (const l of cir.links) {
    const p = l.parentLink || "__root__";
    if (!childrenOf.has(p)) childrenOf.set(p, []);
    childrenOf.get(p).push(l);
  }
  const jointFor = new Map(cir.joints.map((j) => [j.child, j]));
  const out = [`<mujoco model="${esc(cir.name)}">`,
    `  <compiler angle="radian" coordinate="local"/>`,
    `  <option gravity="0 ${cir.coordinateSystem?.upAxis === "Z" ? "0 -9.81" : "-9.81 0"}"/>`,
    `  <worldbody>`];
  const emit = (link, parentFrame, depth) => {
    const pad = "    ".repeat(depth + 1);
    const fr = frame.get(link.id);
    const rel = fr.clone().sub(parentFrame);
    const geoOff = centre.get(link.id).clone().sub(fr);
    const I = link.inertial.inertia.map((r) => r.map(Number));
    out.push(`${pad}<body name="${esc(link.id)}" pos="${xyz(rel.toArray())}">`);
    out.push(`${pad}  <inertial pos="${xyz(new THREE.Vector3().fromArray(link.inertial.com).sub(fr).toArray())}" mass="${f(Math.max(1e-4, link.inertial.mass))}" fullinertia="${f(I[0][0])} ${f(I[1][1])} ${f(I[2][2])} ${f(I[0][1])} ${f(I[0][2])} ${f(I[1][2])}"/>`);
    const j = jointFor.get(link.id);
    if (j && j.type !== "fixed") {
      const kind = j.type === "prismatic" ? "slide" : "hinge";
      const range = j.limits && j.type !== "continuous"
        ? ` range="${f(j.limits.lower)} ${f(j.limits.upper)}" limited="true"` : ` limited="false"`;
      out.push(`${pad}  <joint name="${esc(j.id)}" type="${kind}" axis="${xyz(j.axis)}" pos="0 0 0"${range}/>`);
    }
    for (const s of collisionShapes(link)) {
      const off = geoOff.clone().add(new THREE.Vector3().fromArray(s.offset));
      let attrs = "";
      if (s.kind === "box") attrs = `type="box" size="${xyz(s.size.map((v) => v / 2))}"`;
      else if (s.kind === "sphere") attrs = `type="sphere" size="${f(s.radius)}"`;
      else if (s.kind === "capsule") attrs = `type="capsule" size="${f(s.radius)} ${f(s.length / 2)}"`;
      else attrs = `type="cylinder" size="${f(s.radius)} ${f(s.length / 2)}"`;
      out.push(`${pad}  <geom ${attrs} pos="${xyz(off.toArray())}"/>`);
    }
    for (const c of childrenOf.get(link.id) || []) emit(c, fr, depth + 1);
    out.push(`${pad}</body>`);
  };
  const roots = cir.links.filter((l) => !l.parentLink);
  for (const r of roots) emit(r, new THREE.Vector3(), 1);
  out.push(`  </worldbody>`, `</mujoco>`);
  return out.join("\n");
}

/* ------------------------------------------------- bundle (zip with meshes) */
export function exportBundle(cir, sceneRoot) {
  const files = {};
  files["robot.urdf"] = strToU8(exportURDF(cir));
  files["robot.usda"] = strToU8(exportUSDA(cir));
  files["robot.xml"] = strToU8(exportMJCF(cir));
  files["asset.json"] = strToU8(JSON.stringify(stripCIR(cir), null, 2));
  files["README.txt"] = strToU8([
    `VRINGON Robot Asset — ${cir.name}`,
    ``,
    `robot.usda  마스터 자산 (USD Physics: rigid body / mass / collider / joint / articulation root)`,
    `robot.urdf  ROS·Isaac Sim 용 (visual 은 meshes/*.stl 참조, scale 0.001)`,
    `robot.xml   MuJoCo MJCF`,
    `asset.json  Canonical Intermediate Representation (confidence·provenance 포함)`,
    `meshes/     링크별 시각 메시 (mm 단위 STL)`,
    ``,
    `링크 ${cir.links.length}개 · 조인트 ${cir.joints.length}개`,
    `주의: 질량·관성·가동범위 중 status 가 source_verified 가 아닌 항목은 검토가 필요합니다.`,
  ].join("\n"));
  const stl = new STLExporter();
  for (const l of cir.links) {
    const node = l._measured?.node;
    if (!node) continue;
    const dv = stl.parse(node, { binary: true });
    files[`meshes/${l.id}.stl`] = new Uint8Array(dv.buffer ? dv.buffer : dv);
  }
  return zipSync(files, { level: 6 });
}

/** CIR without viewport-only back-references (safe to serialise) */
export function stripCIR(cir) {
  return {
    ...cir,
    links: cir.links.map(({ _measured, _collision, ...rest }) => rest),
    joints: cir.joints.map(({ _pivotMm, _axis, ...rest }) => rest),
  };
}

/* ------------------------------------------------- export round-trip check */
export async function verifyExports(cir, sceneRoot) {
  const lines = [];
  const dp = new DOMParser();

  const urdf = exportURDF(cir);
  const ud = dp.parseFromString(urdf, "application/xml");
  const uerr = ud.querySelector("parsererror");
  const uLinks = [...ud.querySelectorAll("robot > link")].map((n) => n.getAttribute("name"));
  const uJoints = [...ud.querySelectorAll("robot > joint")];
  const danglingJ = uJoints.filter((j) => {
    const p = j.querySelector("parent")?.getAttribute("link");
    const c = j.querySelector("child")?.getAttribute("link");
    return !uLinks.includes(p) || !uLinks.includes(c);
  });
  if (uerr) lines.push({ level: "err", text: "URDF XML 파싱 실패" });
  else if (danglingJ.length) lines.push({ level: "err", text: `URDF 조인트 ${danglingJ.length}개가 없는 링크를 참조` });
  else lines.push({ level: "ok", text: `URDF 파싱 성공 · 링크 ${uLinks.length} / 조인트 ${uJoints.length} 참조 일치` });

  const mj = exportMJCF(cir);
  const md = dp.parseFromString(mj, "application/xml");
  const mBodies = md.querySelectorAll("body").length;
  if (md.querySelector("parsererror")) lines.push({ level: "err", text: "MJCF XML 파싱 실패" });
  else if (mBodies !== cir.links.length) lines.push({ level: "warn", text: `MJCF body ${mBodies}개 (링크 ${cir.links.length}개)` });
  else lines.push({ level: "ok", text: `MJCF 파싱 성공 · body ${mBodies}개 중첩 계층 일치` });

  const usda = exportUSDA(cir);
  const braces = (usda.match(/{/g) || []).length - (usda.match(/}/g) || []).length;
  const bodyRefs = [...usda.matchAll(/rel physics:body[01] = <\/([^>]+)>/g)].map((m) => m[1].split("/").pop());
  const missing = bodyRefs.filter((r) => !cir.links.some((l) => l.id === r));
  const artRoots = (usda.match(/PhysicsArticulationRootAPI/g) || []).length;
  if (braces !== 0) lines.push({ level: "err", text: `USD 중괄호 불균형 (${braces})` });
  else if (missing.length) lines.push({ level: "err", text: `USD 조인트가 없는 바디 참조 ${missing.length}건` });
  else lines.push({ level: "ok", text: `USD 스키마 검사 통과 · articulation root ${artRoots}개 · 조인트 참조 ${bodyRefs.length}건 유효` });

  if (sceneRoot) {
    try {
      const { GLTFExporter } = await import("three/addons/exporters/GLTFExporter.js");
      const { GLTFLoader } = await import("three/addons/loaders/GLTFLoader.js");
      const buf = await new Promise((res, rej) =>
        new GLTFExporter().parse(sceneRoot, res, rej, { binary: true }));
      const back = await new GLTFLoader().parseAsync(buf, "");
      let meshes = 0;
      back.scene.traverse((o) => { if (o.isMesh) meshes++; });
      lines.push({ level: "ok", text: `GLB 재로딩 성공 · 메시 ${meshes}개 (${(buf.byteLength / 1024).toFixed(0)}KB)` });
    } catch (e) {
      lines.push({ level: "warn", text: `GLB 왕복 확인 실패: ${e.message}` });
    }
  }
  const ok = !lines.some((l) => l.level === "err");
  return { ok, lines };
}
